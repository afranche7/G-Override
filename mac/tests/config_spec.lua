-- The shared config.ini (the same file the Windows Helper reads) plus config.local.ini overrides.
local config = require("g_override.config")
local helpers = require("helpers")

local function tempFile(contents)
  local path = os.tmpname()
  local f = assert(io.open(path, "wb"))
  f:write(contents)
  f:close()
  return path
end

describe("Config", function()
  it("reads the defaults from the shared config.ini", function()
    local cfg = helpers.testConfig()
    assert.are.equal("F17", cfg.triggers.focusClaude)
    assert.are.equal("F18", cfg.triggers.sendToClaude)
    assert.are.equal("F19", cfg.triggers.promptPalette)
    assert.are.equal("com.anthropic.claudefordesktop", cfg.claudeBundleId)
    assert.are.equal("Claude", cfg.claudeAppName)
    assert.are.equal(15000, cfg.launchTimeoutMs)
    assert.is_false(cfg.debug)
  end)

  it("lets config.local.ini override individual keys and keeps the rest", function()
    local localIni = tempFile("[triggers]\nfocus_claude=ctrl+alt+shift+F10\n\n[debug]\nenabled=1\n")
    local cfg = config.load(helpers.REPO_ROOT .. "/config.ini", localIni)
    os.remove(localIni)
    assert.are.equal("ctrl+alt+shift+F10", cfg.triggers.focusClaude)
    assert.are.equal("F18", cfg.triggers.sendToClaude)
    assert.is_true(cfg.debug)
  end)

  it("ignores a config.local.ini that doesn't exist", function()
    local cfg = config.load(helpers.REPO_ROOT .. "/config.ini", helpers.REPO_ROOT .. "/no-such-local.ini")
    assert.are.equal("F17", cfg.triggers.focusClaude)
  end)

  it("fails clearly when the shared config is missing", function()
    assert.has_error(function() config.load(helpers.REPO_ROOT .. "/no-such-config.ini") end)
  end)

  it("falls back to defaults for missing or non-numeric values", function()
    local base = tempFile("[timing]\nlaunch_timeout_ms=soon\n")
    local cfg = config.load(base)
    os.remove(base)
    assert.are.equal("F17", cfg.triggers.focusClaude)
    assert.are.equal("com.anthropic.claudefordesktop", cfg.claudeBundleId)
    assert.are.equal(15000, cfg.launchTimeoutMs)
  end)

  it("parses INI the way AutoHotkey does: comments, spacing, CRLF and case-insensitive names", function()
    local base = tempFile("\239\187\191; comment\r\n[Claude]\r\n  Mac_App_Name = Claude Beta  \r\n# also a comment\r\n")
    local cfg = config.load(base)
    os.remove(base)
    assert.are.equal("Claude Beta", cfg.claudeAppName)
  end)

  it("reads a UTF-16 config.local.ini, as the Windows installer writes it", function()
    local text = "[debug]\r\nenabled=1\r\n"
    local utf16 = "\255\254" .. text:gsub(".", "%0\0")
    local localIni = tempFile(utf16)
    local cfg = config.load(helpers.REPO_ROOT .. "/config.ini", localIni)
    os.remove(localIni)
    assert.is_true(cfg.debug)
  end)

  it("resolves the palette file from the repo root and keeps absolute paths", function()
    assert.are.equal(helpers.REPO_ROOT .. "/palette.md", helpers.testConfig().paletteFile)
    local localIni = tempFile("[palette]\nfile=/Users/me/prompts.md\n")
    local cfg = config.load(helpers.REPO_ROOT .. "/config.ini", localIni)
    os.remove(localIni)
    assert.are.equal("/Users/me/prompts.md", cfg.paletteFile)
  end)
end)
